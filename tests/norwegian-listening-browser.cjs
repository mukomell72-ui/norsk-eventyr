'use strict';
const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=n=>fs.readFileSync(path.join(__dirname,'..',n),'utf8');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setContent('<html lang="ru"><meta name="viewport" content="width=device-width,initial-scale=1"><body><main id="app"></main></body></html>');
  await page.evaluate(()=>{
   window.state={level:'A1',elite:{},dailyDictionary:{},completed:{},story:{completed:{}},streak:0,learningV8:{},xp:0};
   window.esc=text=>String(text??'').replace(/[&<>"']/g,x=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[x]));
   window.saveState=()=>{window.saved=(window.saved||0)+1;};
   window.shell=html=>{document.getElementById('app').innerHTML=html;};
   window.navigate=()=>{};window.nav=()=>'';window.stopTimer=()=>{};window.touchStudy=()=>{};
   window.cloudLink=()=>null;window.neLocalDate=()=> '2026-10-18';
   window.NEResources={byLevel:()=>[]};
   window.speechCalls=[];window.speakText=async text=>{window.speechCalls.push(text);return {source:'ai'};};
  });
  await page.addScriptTag({content:read('norwegian-listening.js')});
  await page.addScriptTag({content:read('elite.js')});
  await page.evaluate(()=>window.renderListeningLab());
  assert(await page.getByRole('heading',{name:'Слушаем норвежский'}).isVisible());
  assert.equal(await page.locator('[data-norwegian-lesson]').count(),2);
  assert(!await page.locator('details.ne-english-archive').evaluate(el=>el.open),'English archive must be collapsed');
  assert.equal(await page.locator('.fsi-audio-list-v63 audio').count(),8);
  await page.locator('details.ne-english-archive summary').click();
  await page.locator('audio[aria-label="Архивная запись 3"]').evaluate(el=>el.dispatchEvent(new Event('error')));
  assert((await page.locator('#fsi-error-2').innerText()).includes('не загрузился'),'Failed third tape reports real error');
  await page.getByRole('button',{name:'Начать слушать'}).first().click();
  assert(await page.locator('[data-listen-task="a1-intro"]').isVisible());
  assert.equal(await page.locator('.ne-audio-lesson [lang="nb"]').count(),0,'Transcript starts hidden for auditory practice');
  await page.locator('.ne-audio-lesson .choice').nth(1).click();
  assert((await page.locator('#neListenFeedback').innerText()).includes('Сначала прослушай'));
  await page.getByRole('button',{name:'Слушать по-норвежски'}).click();
  assert.equal((await page.evaluate(()=>window.speechCalls))[0], 'Hei, jeg heter Mari. Hva heter du? Jeg heter Ola. Hyggelig å møte deg!');
  await page.locator('.ne-audio-lesson .choice').nth(0).click();
  assert((await page.locator('#neListenFeedback').innerText()).includes('Пока неверно'));
  await page.locator('.ne-audio-lesson .choice').nth(1).click();
  assert((await page.locator('#neListenFeedback').innerText()).includes('Верно'));
  await page.getByRole('button',{name:'Следующий вопрос'}).click();
  await page.locator('.ne-audio-lesson .choice').nth(2).click();
  await page.getByRole('button',{name:'Закончить тренировку'}).click();
  assert(await page.getByRole('heading',{name:'Тренировка завершена'}).isVisible());
  const result=await page.evaluate(()=>({progress:window.state.elite.norwegianListeningProgress['a1-intro'],count:window.state.elite.counts.listening}));
  assert.equal(result.progress.firstTry,1,'Wrong first answer reduces accuracy');
  assert.equal(result.progress.withAudio,true);
  assert.equal(result.count,1,'Completed real playback marks practice exactly once, without CEFR certification');
  await page.evaluate(()=>window.navigate('listeninglab'));
  await page.evaluate(()=>{window.speakText=async()=>({source:'unavailable'})});
  await page.getByRole('button',{name:'Начать слушать'}).nth(1).click();
  await page.getByRole('button',{name:'Слушать по-норвежски'}).click();
  assert((await page.locator('#neListenStatus').innerText()).includes('Звук не запустился'));
  await page.getByRole('button',{name:'Показать текст и перевод'}).click();
  assert(await page.locator('.ne-audio-lesson [lang="nb"]').isVisible());
  await page.locator('.ne-audio-lesson .choice').nth(0).click();
  await page.getByRole('button',{name:'Следующий вопрос'}).click();
  await page.locator('.ne-audio-lesson .choice').nth(1).click();
  await page.getByRole('button',{name:'Закончить тренировку'}).click();
  const unvoiced=await page.evaluate(()=>({progress:window.state.elite.norwegianListeningProgress['a1-bus'],count:window.state.elite.counts.listening}));
  assert.equal(unvoiced.progress.withAudio,false);
  assert.equal(unvoiced.count,1,'Reading a revealed transcript does not count as listening');
  await page.evaluate(()=>{window.state.level='B1';window.navigate('listeninglab');});
  assert.equal(await page.locator('[data-norwegian-lesson="b1-work"]').count(),1);
  assert.equal(await page.locator('[data-norwegian-lesson="a1-intro"]').count(),0);
  assert.deepEqual(errors,[],'No JS exceptions in Listening Lab mobile path');
  console.log('PASS mobile Norwegian Listening Lab: Norwegian-first, audio answer gate, Russian feedback, legacy errors, credit integrity, B1 filter');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
