'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const script=fs.readFileSync(path.join(__dirname,'..','adaptive-teacher.js'),'utf8');
const sandbox={window:{},Date,Math,Number,Object,Array,String,JSON,Set,Intl};
vm.runInNewContext(script,sandbox,{filename:'adaptive-teacher.js'});
const checkpoint=sandbox.window.NEAdaptive?.weeklyCheckpoint;
assert.equal(typeof checkpoint,'function');
const now=new Date('2026-10-22T12:00:00Z');
const history=(date,level='A1',complete=true,score=78)=>({date,level,complete,score});
assert.equal(checkpoint({},'A1',now).due,true,'A new learner needs a baseline assessment');
assert.equal(checkpoint({testHistory:[history('2026-10-21T12:00:00Z','A1',false)]},'A1',now).due,true,'Partial tests cannot reset the reminder');
assert.equal(checkpoint({testHistory:[history('2026-10-20T12:00:00Z','B1')]},'A1',now).due,true,'A test on another CEFR level is not evidence for A1');
const fresh=checkpoint({testHistory:[history('2026-10-19T12:00:00Z')]},'A1',now);
assert.equal(fresh.due,false);
assert.equal(fresh.nextIn,4);
assert.equal(fresh.lastScore,78);
assert.equal(checkpoint({testHistory:[history('2026-10-15T12:00:00Z')]},'A1',now).due,true,'At day seven a new check is due');
const mixed=checkpoint({testHistory:[history('2026-10-01T12:00:00Z'),history('2026-10-20T12:00:00Z')]},'A1',now);
assert.equal(mixed.nextIn,5,'Use most recent completed assessment, not oldest');
assert(script.includes('Контроль недели')&&script.includes('Пройти контроль'),'Teacher dashboard must expose independent review');
console.log('PASS: weekly diagnostics only use completed, level-scoped evidence');
