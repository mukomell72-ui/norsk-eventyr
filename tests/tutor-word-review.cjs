'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),code=fs.readFileSync(path.join(root,'lesson-vocabulary-trays.js'),'utf8');
const state={level:'A1',dailyDictionary:{},srs:{},wordPracticeQueue:{}};
const other={level:'A1',learningV8:{},dailyDictionary:{},srs:{},wordPracticeQueue:{}};
let saves=0;
const window={neLearnerState:state,saveState:()=>{saves++}};
const lesson={id:'a1-job',level:'A1',vocab:[['å jobbe','работать'],['en jobb','работа'],['å bo','жить']]};
const dom={getElementById:()=>null,createElement:()=>({}),head:{appendChild(){}}};
vm.runInNewContext(code,{window,document:dom,COURSE:[lesson],Date,Math,Intl,Set,Map,Object,Number,Array,JSON,String});
const trays=window.NEWordTrays;
assert.equal(trays.recordTutorWord({question:'Jeg ... забыл как сказать работаю',explanation:'Å jobbe — работать. Jeg jobber.',lesson}),'å jobbe');
assert.equal(state.dailyDictionary.jobbe.translation_ru,'работать');
assert.equal(state.dailyDictionary.jobbe.correct,0,'A hint is not an independent correct answer');
assert.equal(state.dailyDictionary.jobbe.wrong,0,'A hint is not an assessed failure');
assert(state.dailyDictionary.jobbe.nextDue>Date.now(),'Tutor explanation should enter delayed review');
assert(state.srs.jobbe.due>Date.now());
assert(state.wordPracticeQueue.jobbe>0);
const before=saves;
assert.equal(trays.recordTutorWord({question:'забыл как будет работать',explanation:'Å jobbe, jeg jobber.',lesson}),'å jobbe');
assert.equal(saves,before,'Same-day repeated question cannot double count');
assert.equal(trays.recordTutorWord({question:'Объясни порядок слов',explanation:'Å bo — жить',lesson}),null);
assert.equal(trays.recordTutorWord({question:'Что значит летающий?',explanation:'Å fly — летать',lesson}),null,
 'No words may be invented from an AI answer outside the known course');
assert.equal(trays.recordTutorWord({question:'что значит bo?',explanation:'Не знаю.',lesson}),null);
window.neLearnerState=other;
assert.equal(trays.recordTutorWord({question:'забыл как сказать живу',explanation:'Å bo — жить',lesson}),'å bo');
assert.equal(state.dailyDictionary.bo,undefined,'Account review data must be isolated');
assert.equal(other.dailyDictionary.bo.translation_ru,'жить');
assert.equal(other.dailyDictionary.bo.correct,0);
assert(fs.readFileSync(path.join(root,'ui-v7.js'),'utf8').includes('NEWordTrays?.recordTutorWord?.('));
assert(fs.readFileSync(path.join(root,'visual-world.js'),'utf8').includes('NEWordTrays?.recordTutorWord?.('));
console.log('PASS tutor word review: verified lexical match, delayed SRS, no mastery, idempotence, account isolation');
