'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=name=>fs.readFileSync(path.join(root,name),'utf8');
const state={learningV8:{}},spoken=[];
const own={hidden:true},ownWords={textContent:''},portrait={src:'',parentElement:{setAttribute(){}}};
const nodes={neSceneOwn:own,neSceneOwnWords:ownWords,neWorldSelfImage:portrait,neSceneOwnAvatar:{src:''},neWorldVoiceStatus:{textContent:''}};
const document={getElementById:id=>nodes[id]||null,querySelector:()=>null,querySelectorAll:()=>[]};
const lesson={id:'a1-home',level:'A1',_adaptive:{moduleId:'a1-home',storyVariant:0}};
const session={lesson,guidedSpeech:{lessonId:'a1-home',index:0,turns:[]}};
let saved=0;
const window={neLearnerState:state,neLessonSession:session,saveState:()=>{saved++;return true},
 freeEx:()=>'<legacy>',checkFree:()=>'<legacy>',
 speakText:(...args)=>{spoken.push(args);return {addEventListener(){}}}};
const esc=value=>String(value??'').replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
vm.runInNewContext(read('scene-course.js'),{window,document},{filename:'scene-course.js'});
vm.runInNewContext(read('visual-world.js'),{window,document},{filename:'visual-world.js'});
vm.runInNewContext(read('guided-speaking.js'),{window,document,esc},{filename:'guided-speaking.js'});
const course=window.NESceneCourse,visual=window.NEVisualWorld;
assert.deepEqual(Array.from(course.modules),['a1-foundation','a1-home']);
const scene=window.NEGuidedSpeaking.definition(lesson);
assert.equal(scene.steps.length,3,'Original evaluated turns must be retained');
const first=window.freeEx(lesson,'speaking');
assert(first.includes('Нора знакомит тебя с участниками'));
assert(first.includes('Нора объясняет:'));
assert(first.includes('Ингрид → тебе'));
assert.equal((first.match(/id="freeAnswer"/g)||[]).length,1);
assert(!first.includes('Spør hvor nøkkelen er. Si hvor du leter etter den.'),'Old static prompt must not contradict the active turn');
session.guidedSpeech.index=1;
session.guidedSpeech.turns=[{answer:'Hvor er nøkkelen?',reply:'Nøkkelen ligger på bordet.'}];
const group=window.freeEx(lesson,'speaking');
assert(group.includes('Эрик → Ингрид'),'Other characters must speak to each other');
assert(group.includes('NEVisualWorld.speakAside(0)'));
assert(group.includes('ne-world-history'),'History remains visible on demand');
assert(visual.speakAside(0));
assert.equal(spoken.at(-1)[3],'cedar','Erik has his own playback voice');
assert(visual.speakPartner());
assert.equal(spoken.at(-1)[3],'coral','Ingrid has her own playback voice');
assert(visual.speakLesson());
assert.equal(spoken.at(-1)[3],'marin','Nora speaks explanations');
visual.accepted('Jeg leter etter nøkkelen ved døra.','Se ved vinduet.');
assert.equal(own.hidden,false,'Accepted user turn becomes visible with the avatar');
assert.equal(ownWords.textContent,'Jeg leter etter nøkkelen ved døra.');
assert(visual.chooseGender('female'));
assert.equal(state.learningV8.visualWorld.avatar,'ingrid');
assert.equal(state.learningV8.visualWorld.gender,'female');
assert(visual.chooseGender('male'));
assert.equal(state.learningV8.visualWorld.avatar,'erik');
assert.equal(state.learningV8.visualWorld.gender,'male');
assert(!visual.chooseGender('invalid'));
assert(visual.avatarSettings().includes('Женский'));
const previous=JSON.stringify(session.guidedSpeech);
assert.equal(course.forTurn({...lesson,_adaptive:{moduleId:'a1-home',storyVariant:1}},scene,1),null,'Keep story variants untouched');
assert.equal(JSON.stringify(session.guidedSpeech),previous,'Presentation cannot alter graded progress');
const foundation={id:'a1-foundation',level:'A1',_adaptive:{moduleId:'a1-foundation',storyVariant:0}};
const f=window.NEGuidedSpeaking.definition(foundation);
assert.equal(f.steps.length,8);
assert.equal(course.forTurn(foundation,f,0).speaker.name,'Сотрудник','Do not reveal Erik before introduction');
assert(course.forTurn(foundation,f,5).participants.some(x=>x.id==='ingrid'),'Introduce group member later');
assert(!visual.tapWords('<script>x</script>').includes('<script>'),'Escaping retained');
assert(read('access.js').includes("'scene-course.js','story-journey-advanced.js'"),'Load authored scene before visual UI');
assert(read('sw.js').includes('/scene-course.js?v=8.3.0'),'Precache offline scene engine');
assert(read('visual-world.css').includes('.ne-scene-gender'),'Gender buttons have styles');
console.log('PASS: scene-course 2 modules, 11 authored turns, avatar gender, group dialogue, voice routing, independent evaluation');
